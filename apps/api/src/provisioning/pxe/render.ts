import { z } from 'zod';

/**
 * The PXE service (dnsmasq: proxy DHCP or DHCP, plus TFTP for iPXE).
 *
 * The worker writes a small JSON "desired state" (settings + the MACs of
 * servers with an active network install); a root-run helper validates it with
 * this schema and renders dnsmasq's configuration from it. The worker never
 * writes dnsmasq configuration itself: dnsmasq starts as root, and free-form
 * configuration could make it run commands. Only the validated fields below
 * reach the file, so the worst a compromised worker could do is change which
 * known MACs are answered.
 *
 * dnsmasq answers only MACs in the active list (dhcp-ignore=tag:!nexora): no
 * other device on the network ever gets an address or boot offer from it.
 */

const ipv4 = z.string().regex(/^(25[0-5]|2[0-4]\d|1?\d?\d)(\.(25[0-5]|2[0-4]\d|1?\d?\d)){3}$/);
const cidr4 = z.string().regex(/^(25[0-5]|2[0-4]\d|1?\d?\d)(\.(25[0-5]|2[0-4]\d|1?\d?\d)){3}\/([0-9]|[12]\d|3[0-2])$/);
const mac = z.string().regex(/^([0-9a-f]{2}:){5}[0-9a-f]{2}$/);

export const pxeDesiredSchema = z
  .object({
    version: z.literal(1),
    enabled: z.boolean(),
    mode: z.enum(['proxy', 'dhcp', 'external']),
    interface: z
      .string()
      .regex(/^[A-Za-z0-9_.:@-]{1,32}$/)
      .nullable(),
    serverAddress: ipv4,
    proxyNetworks: z.array(cidr4).max(16),
    ranges: z.array(z.object({ network: cidr4, start: ipv4, end: ipv4, gateway: ipv4.nullable().optional(), dns: z.array(ipv4).max(3) }).strict()).max(16),
    /** http://host[:port], no path: iPXE chains to <bootBase>/api/v1/boot/ipxe. */
    bootBase: z.string().regex(/^http:\/\/[A-Za-z0-9.-]+(:\d{1,5})?$|^http:\/\/\[[0-9a-fA-F:]+\](:\d{1,5})?$/),
    macs: z.array(mac).max(4096),
  })
  .strict();
export type PxeDesired = z.infer<typeof pxeDesiredSchema>;

export function netmask(prefix: number) {
  const m = prefix === 0 ? 0 : (0xffffffff << (32 - prefix)) >>> 0;
  return [24, 16, 8, 0].map((s) => (m >>> s) & 255).join('.');
}
const network = (c: string) => {
  const [a, l] = c.split('/') as [string, string];
  const ip = a.split('.').reduce((n, o) => ((n << 8) | Number(o)) >>> 0, 0);
  const m = Number(l) === 0 ? 0 : (0xffffffff << (32 - Number(l))) >>> 0;
  const net = (ip & m) >>> 0;
  return { addr: [24, 16, 8, 0].map((s) => (net >>> s) & 255).join('.'), mask: netmask(Number(l)) };
};

export interface RenderPaths {
  hostsDir: string;
  tftpRoot: string;
  /** Written by dnsmasq after it drops privileges (its directory is owned by that user). */
  leaseFile?: string;
  /** User dnsmasq drops to after binding its ports. */
  user: string;
  group: string;
}

/** dnsmasq configuration for the desired state (DHCP parts left out in "external" mode). */
export function renderDnsmasq(d: PxeDesired, p: RenderPaths): string {
  const L: string[] = [
    '# Generated by NexoraDC from OS & Images → PXE service. Changes here are overwritten.',
    'port=0',
    `user=${p.user}`,
    `group=${p.group}`,
    'log-facility=-',
    'log-dhcp',
    'bind-dynamic',
    'except-interface=lo',
    ...(d.interface ? [`interface=${d.interface}`] : []),
    'enable-tftp',
    `tftp-root=${p.tftpRoot}`,
  ];
  if (d.mode !== 'external') {
    L.push(
      '',
      '# Only servers with an active NexoraDC network install are answered.',
      `dhcp-hostsdir=${p.hostsDir}`,
      ...(p.leaseFile ? [`dhcp-leasefile=${p.leaseFile}`] : []),
      'dhcp-ignore=tag:!nexora',
      'dhcp-match=set:efi64,option:client-arch,7',
      'dhcp-match=set:efi64,option:client-arch,9',
    );
  }
  if (d.mode === 'proxy') {
    L.push('', '# Proxy DHCP: your DHCP server gives the address; this only adds the boot file.');
    for (const c of d.proxyNetworks) {
      const n = network(c);
      L.push(`dhcp-range=${n.addr},proxy,${n.mask}`);
    }
    L.push('pxe-service=tag:!efi64,x86PC,"NexoraDC network install",undionly', 'pxe-service=tag:efi64,X86-64_EFI,"NexoraDC network install",snponly.efi');
  }
  if (d.mode === 'dhcp') {
    L.push('', '# DHCP for servers being installed (directly or through a DHCP relay).');
    d.ranges.forEach((r, i) => {
      const n = network(r.network);
      L.push(`dhcp-range=set:r${i},${r.start},${r.end},${n.mask},15m`);
      if (r.gateway) L.push(`dhcp-option=tag:r${i},option:router,${r.gateway}`);
      if (r.dns.length) L.push(`dhcp-option=tag:r${i},option:dns-server,${r.dns.join(',')}`);
    });
    L.push(`dhcp-boot=tag:!efi64,undionly.kpxe,,${d.serverAddress}`, `dhcp-boot=tag:efi64,snponly.efi,,${d.serverAddress}`);
  }
  return `${L.join('\n')}\n`;
}

/** Host entries (dhcp-hostsdir format): each active MAC gets the "nexora" tag. */
export function renderHosts(d: PxeDesired): string {
  return `${['# Servers with an active NexoraDC network install', ...[...new Set(d.macs)].sort().map((m) => `${m},set:nexora`)].join('\n')}\n`;
}

/** Fetched over TFTP by NexoraDC's iPXE (its built-in script), then chains to the API. */
export function renderNexoraIpxe(d: PxeDesired): string {
  return ['#!ipxe', '# Generated by NexoraDC. A server without an active install is sent to its next boot device.', `chain ${d.bootBase}/api/v1/boot/ipxe?mac=\${netX/mac} || exit`, ''].join('\n');
}
